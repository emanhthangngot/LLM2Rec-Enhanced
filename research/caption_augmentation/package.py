def _code_cell(source: str) -> dict[str, object]:
    lines = source.splitlines(keepends=True)
    return {"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [], "source": lines}


def notebook_source(bundle: bytes, stage: str, package_dir: Path | None = None) -> str:
    if stage not in NOTEBOOK_STAGE_CELLS:
        raise ValueError(f"no notebook cells registered for stage {stage!r}")
    entry = NOTEBOOK_STAGE_CELLS[stage]
    if stage in INLINE_STAGES:
        cell_bodies = entry(package_dir or Path(__file__).parent)
        cells = [_code_cell(body) for body in cell_bodies]
    else:
        encoded = base64.b64encode(bundle).decode("ascii")
        cells = [_code_cell(_extraction_cell(encoded))]
        cells.extend(_code_cell(body) for body in entry)
    notebook = {
        "cells": cells,
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python", "version": "3.12"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }
    return json.dumps(notebook, indent=1)

def write_kernel_package(
    package_dir: Path,
    output_dir: Path,
    kernel_id: str,
    title: str,
    stage: str = "preflight",
    dataset_sources: list[str] | None = None,
    kernel_sources: list[str] | None = None,
    notebook: bool = False,
    accelerator: str = "NvidiaTeslaT4",
) -> dict[str, object]:
    if stage == VIDEO_GAMES_STAGE:
        # Fail closed before any Video_Games catalog job is packaged.
        from video_games_pilot import validate_pilot_review

        validate_pilot_review(
            PILOT_REVIEW_DIR / "label_sheet_ai_draft.csv",
            PILOT_REVIEW_DIR / "assistant_visual_audit_manifest.json",
        )
    bundle, member_hashes = source_bundle(package_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    if notebook:
        code_file = "runner.ipynb"
        runner = notebook_source(bundle, stage=stage, package_dir=package_dir).encode("utf-8")
    else:
        code_file = "runner.py"
        runner = runner_source(bundle, stage=stage).encode("utf-8")
    (output_dir / code_file).write_bytes(runner)
    metadata = {
        "id": kernel_id,
        "title": title,
        "code_file": code_file,
        "language": "python",
        "kernel_type": "notebook" if notebook else "script",
        "is_private": True,
        "enable_gpu": True,
        "enable_tpu": False,
        "enable_internet": True,
        "keywords": [],
        "dataset_sources": list(dataset_sources or []),
        "kernel_sources": list(kernel_sources or []),
        "competition_sources": [],
        "model_sources": [],
        "machine_shape": accelerator,
    }
    (output_dir / "kernel-metadata.json").write_text(json.dumps(metadata, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    manifest = {
        "stage": stage,
        "notebook": notebook,
        "bundle_sha256": sha256_bytes(bundle),
        "runner_sha256": sha256_bytes(runner),
        "members": member_hashes,
        "metadata_sha256": sha256_bytes((output_dir / "kernel-metadata.json").read_bytes()),
    }
    (output_dir / "package-manifest.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return manifest


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--package-dir", type=Path, default=Path(__file__).parent)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--kernel-id", required=True)
    parser.add_argument("--title", required=True)
    parser.add_argument("--stage", default="preflight")
    parser.add_argument("--dataset-sources", default="", help="comma-separated Kaggle dataset refs to mount")
    parser.add_argument("--kernel-sources", default="", help="comma-separated Kaggle kernel refs to mount (self-reference to resume from a prior push's output)")
    parser.add_argument(
        "--accelerator",
        choices=("NvidiaTeslaT4", "NvidiaTeslaP100", "NvidiaL4"),
        default="NvidiaTeslaT4",
        help="Kaggle GPU machine shape recorded in kernel metadata",
    )
    parser.add_argument("--notebook", action="store_true", help="emit runner.ipynb (kernel_type=notebook) instead of runner.py")
    args = parser.parse_args()
    dataset_sources = [item for item in args.dataset_sources.split(",") if item]
    kernel_sources = [item for item in args.kernel_sources.split(",") if item]
    print(json.dumps(
        write_kernel_package(
            args.package_dir, args.output_dir, args.kernel_id, args.title,
            stage=args.stage, dataset_sources=dataset_sources, kernel_sources=kernel_sources,
            notebook=args.notebook, accelerator=args.accelerator,
        ),
        indent=2, sort_keys=True,
    ))



if __name__ == "__main__":
    main()
