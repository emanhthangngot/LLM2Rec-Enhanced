_LOCAL_MODULE_NAMES = ("corpus", "caption", "crosswalk", "smoke", "pipeline", "video_games_pilot")


def _strip_local_imports(source: str) -> str:
    """Remove intra-package `import X` / `from X import ...` lines (single-
    or multi-line parenthesized) referencing this package's own sibling
    modules, keeping every other line byte-for-byte identical.

    Used to inline a tested module's real source directly as a plain
    notebook cell: once an earlier cell has executed a sibling module's
    source into the shared notebook namespace, its names are already
    defined, so the cross-module import line would be both unnecessary and
    unresolvable (there is no real `crosswalk` package on Kaggle in inline
    mode, only the executed cell's globals).
    """
    local_prefixes = tuple(f"from {name} import" for name in _LOCAL_MODULE_NAMES) + tuple(
        f"import {name}" for name in _LOCAL_MODULE_NAMES
    )
    lines = source.splitlines(keepends=True)
    kept: list[str] = []
    index = 0
    while index < len(lines):
        stripped = lines[index].strip()
        if stripped.startswith(local_prefixes):
            if "(" in stripped and ")" not in stripped:
                index += 1
                while index < len(lines) and ")" not in lines[index]:
                    index += 1
                index += 1
            else:
                index += 1
            continue
        kept.append(lines[index])
        index += 1
    return "".join(kept)


def _module_cell(package_dir: Path, name: str) -> str:
    """Return one sibling module's real source, ready to run as a plain
    notebook cell with zero zip/base64 wrapping (see ISSUES.md #23)."""
    source = (package_dir / name).read_text(encoding="utf-8")
    return _strip_local_imports(source)


