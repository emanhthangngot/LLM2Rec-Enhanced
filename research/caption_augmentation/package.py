def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def source_bundle(package_dir: Path) -> tuple[bytes, dict[str, str]]:
    entries: dict[str, bytes] = {}
    for name in PACKAGE_FILES:
        path = package_dir / name
        if not path.is_file():
            raise FileNotFoundError(f"package source missing: {path}")
        entries[f"visual_delta_fusion/{name}"] = path.read_bytes()
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for member, payload in sorted(entries.items()):
            info = zipfile.ZipInfo(member, date_time=(2020, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            archive.writestr(info, payload)
    return buffer.getvalue(), {member: sha256_bytes(payload) for member, payload in entries.items()}


